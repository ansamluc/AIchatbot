// For Hero Matching: randomly flip an item between two directions:
//   forward  → "What did <Hero> do?" with deed options (original)
//   reverse  → "Who did this deed? <deed>" with hero-name options
// This keeps the quiz fresh and tests recall in both directions.
function mixMatchItem(item, allMatchItems) {
  // ~50% chance to flip to reverse direction
  const flip = Math.random() < 0.5;
  if (!flip || !Array.isArray(allMatchItems) || allMatchItems.length < 2) {
    return { ...item, _kind: 'mc' };
  }
  // Build reverse-direction question
  const correctDeed = item.options[item.answer];
  const correctHero = item.hero;
  // Distractor heroes drawn from other items in this unit
  const others = allMatchItems
    .filter(x => x.hero && x.hero !== correctHero)
    .map(x => x.hero);
  // Shuffle and pick up to 3 distractors
  for (let i = others.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [others[i], others[j]] = [others[j], others[i]];
  }
  const distractors = others.slice(0, 3);
  const heroOptions = [correctHero, ...distractors];
  // Shuffle option order so the answer isn't always first
  for (let i = heroOptions.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [heroOptions[i], heroOptions[j]] = [heroOptions[j], heroOptions[i]];
  }
  const answerIdx = heroOptions.indexOf(correctHero);
  return {
    _kind: 'mc',
    q: `<em>Which hero did this?</em><br>&ldquo;${correctDeed}&rdquo;`,
    options: heroOptions,
    answer: answerIdx,
    explain: item.explain
  };
}

function buildSSQuizPool(quizType) {
  const u = SS_UNITS[state.currentUnit];
  let pool = [];
  if (quizType === 'mc') {
    pool = u.quiz_mc.map(item => ({ ...item, _kind: 'mc' }));
  } else if (quizType === 'tf') {
    pool = u.quiz_tf.map(item => ({ ...item, _kind: 'tf' }));
  } else if (quizType === 'fill') {
    pool = u.quiz_fill.map(item => ({ ...item, _kind: 'fill' }));
  } else if (quizType === 'match') {
    pool = (u.quiz_match || []).map(item => mixMatchItem(item, u.quiz_match));
  } else if (quizType === 'mix') {
    pool = [
      ...u.quiz_mc.map(i => ({ ...i, _kind: 'mc' })),
      ...u.quiz_tf.map(i => ({ ...i, _kind: 'tf' })),
      ...u.quiz_fill.map(i => ({ ...i, _kind: 'fill' })),
      ...((u.quiz_match || []).map(i => mixMatchItem(i, u.quiz_match)))
    ];
  }
  // Shuffle and take up to 10
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  return pool.slice(0, Math.min(10, pool.length));
}

function startSSQuiz(quizType) {
  state.mode = 'ss_quiz';
  state.quizIndex = 0;
  state.quizCorrect = 0;
  state.ssQuizType = quizType;
  state.ssQuizPool = buildSSQuizPool(quizType);
  const u = SS_UNITS[state.currentUnit];
  const labels = { mc: 'Multiple Choice', tf: 'True or False', fill: 'Fill-in-the-Blank', match: 'Hero Matching', mix: 'Mixed' };
  botSay(
    `<strong>⚔ Trial of Citizenship: ${u.title} — ${labels[quizType]}</strong><br>` +
    `<em>${state.ssQuizPool.length} sacred questions await thee. Steel thy mind — the trial begins!</em>`
  );
  setTimeout(askSSQuestion, 500);
}

function askSSQuestion() {
  const item = state.ssQuizPool[state.quizIndex];
  let qHTML = `<strong>Trial ${state.quizIndex + 1} of ${state.ssQuizPool.length}</strong><br><br>${item.q}`;

  let opts;
  if (item._kind === 'tf') {
    opts = [
      { label: '✓ True', onClick: (btn) => handleSSAnswer(true, btn) },
      { label: '✗ False', onClick: (btn) => handleSSAnswer(false, btn) }
    ];
  } else {
    opts = item.options.map((opt, idx) => ({
      label: opt,
      onClick: (btn) => handleSSAnswer(idx, btn)
    }));
  }
  botSay(qHTML, opts);
}

function handleSSAnswer(chosen, btn) {
  const item = state.ssQuizPool[state.quizIndex];
  const allBtns = btn.parentElement.querySelectorAll('button');
  allBtns.forEach(b => b.disabled = true);

  let correct;
  let chosenLabel;
  let truthLabelForLog;
  if (item._kind === 'tf') {
    correct = (chosen === item.answer);
    chosenLabel = chosen ? 'True' : 'False';
    truthLabelForLog = item.answer ? 'True' : 'False';
  } else {
    correct = (chosen === item.answer);
    chosenLabel = item.options[chosen];
    truthLabelForLog = item.options[item.answer];
  }
  userSay(chosenLabel);

  if (correct) {
    btn.classList.add('correct');
    state.quizCorrect++;
    addStars(1);
    botSay(`<div class='feedback-correct'>✠ <strong>Victory!</strong> ${item.explain}<br><em>+1 Honour</em></div>`);
  } else {
    btn.classList.add('wrong');
    let truthLabel;
    if (item._kind === 'tf') {
      truthLabel = item.answer ? 'True' : 'False';
      const truthIdx = item.answer ? 0 : 1;
      allBtns[truthIdx].classList.add('correct');
    } else {
      truthLabel = item.options[item.answer];
      allBtns[item.answer].classList.add('correct');
    }
    botSay(
      `<div class='feedback-wrong'>⚔ <strong>The truth was &ldquo;${truthLabel}&rdquo;.</strong><br>` +
      `${item.explain}<br><em>Stand firm, scholar — thou shalt prevail!</em></div>`
    );
  }
  const ssOpts = item._kind === 'tf' ? ['True', 'False'] : (item.options || null);
  logAnswer(correct, item.q, chosenLabel, truthLabelForLog, item.explain, ssOpts);

  state.quizIndex++;
  setTimeout(() => {
    if (state.quizIndex < state.ssQuizPool.length) {
      askSSQuestion();
    } else {
      finishSSQuiz();
    }
  }, 900);
}

function finishSSQuiz() {
  const u = SS_UNITS[state.currentUnit];
  const total = state.ssQuizPool.length;
  const got = state.quizCorrect;
  const bonus = (got === total) ? 3 : (got >= total - 1) ? 2 : (got >= total / 2) ? 1 : 0;
  let msg;
  if (got === total) {
    msg = `✠✠✠ <strong>GLORIOUS VICTORY!</strong> All ${total} trials of citizenship conquered! <em>The Republic is proud of thee!</em> Bonus +${bonus} Honour!`;
  } else if (got >= total - 1) {
    msg = `⚔ <strong>Most valiant!</strong> Thou hast bested ${got} of ${total} trials. Bonus +${bonus} Honour!`;
  } else if (got >= total / 2) {
    msg = `✠ <strong>A worthy showing!</strong> ${got} of ${total} trials won. Bonus +${bonus} Honour. <em>Study the lesson once more, citizen-scholar!</em>`;
  } else {
    msg = `Thou hast claimed ${got} of ${total} trials. <em>Even great citizens return to study. Let us read the lesson anew!</em>`;
  }
  if (bonus) addStars(bonus);

  botSay(
    msg,
    [
      { label: "🎲 Another Set of Questions", onClick: () => { userSay("Another set of questions"); startSSQuiz(state.ssQuizType); } },
      { label: "📜 Return to the Lesson", onClick: () => { userSay("Return to lesson"); startSSLesson(); } },
      { label: "🔑 Vocabulary Review", onClick: () => { userSay("Vocabulary review"); startSSVocab(); } },
      { label: "📖 Choose Another Lesson", onClick: () => { userSay("Choose another lesson"); showUnitMenu(); } },
      { label: "🏛 Change Library", onClick: () => { userSay("Change library"); showSectionMenu(); } }
    ]
  );
}

